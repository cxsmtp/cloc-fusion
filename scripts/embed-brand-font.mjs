#!/usr/bin/env node
// Regenerate src/report/brand-fonts.js from assets/fonts/founders-grotesk/: the brand typeface,
// embedded into the standalone page and the HTML reports when licensed font files are supplied
// (see that folder's README). With no files, the module is empty and the font is used only where
// it is installed.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';

const DIR = 'assets/fonts/founders-grotesk';
const WEIGHTS = { thin: 100, extralight: 200, light: 300, regular: 400, book: 400, medium: 500, semibold: 600, bold: 700, extrabold: 800, black: 900 };
const FORMATS = { woff2: 'woff2', woff: 'woff', otf: 'opentype', ttf: 'truetype' };
const faces = [];
for (const file of existsSync(DIR) ? readdirSync(DIR).sort() : []) {
  const ext = file.split('.').pop().toLowerCase();
  if (!FORMATS[ext] || /italic|cond/i.test(file)) continue; // upright, normal width only
  const key = Object.keys(WEIGHTS)
    .sort((a, b) => b.length - a.length)
    .find((w) => file.toLowerCase().replace(/[-_ ]/g, '').includes(w));
  const weight = WEIGHTS[key || 'regular'];
  if (faces.some((f) => f.weight === weight && f.format === 'woff2')) continue; // one file per weight, woff2 preferred
  faces.push({ weight, format: FORMATS[ext], mime: ext === 'woff2' ? 'font/woff2' : ext === 'woff' ? 'font/woff' : ext === 'otf' ? 'font/otf' : 'font/ttf', data: readFileSync(`${DIR}/${file}`).toString('base64') });
}
writeFileSync('src/report/brand-fonts.js', `// Generated by scripts/embed-brand-font.mjs from ${DIR}. Do not edit.\nexport const BRAND_FONT_FACES = ${JSON.stringify(faces)};\n`);
console.log(`src/report/brand-fonts.js: ${faces.length ? faces.map((f) => f.weight).join(', ') : 'no font files (the font is used where installed)'}`);
