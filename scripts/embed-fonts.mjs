#!/usr/bin/env node
// Regenerate src/report/fonts.js from assets/fonts/*.woff2: the next-gen look's fonts (Plus Jakarta
// Sans, JetBrains Mono; SIL Open Font License 1.1, see assets/fonts/OFL.txt), embedded so the HTML
// report is one file that renders the same offline, on any machine.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';

const faces = [];
for (const file of readdirSync('assets/fonts').filter((f) => f.endsWith('.woff2')).sort()) {
  const m = file.match(/^(plus-jakarta-sans|jetbrains-mono)-latin-(\d+)-normal\.woff2$/);
  if (!m) continue;
  faces.push({ family: m[1] === 'jetbrains-mono' ? 'CF Mono' : 'CF Jakarta', weight: Number(m[2]), data: readFileSync(`assets/fonts/${file}`).toString('base64') });
}
writeFileSync(
  'src/report/fonts.js',
  `// Generated by scripts/embed-fonts.mjs from assets/fonts (SIL Open Font License 1.1). Do not edit.\nexport const FONT_FACES = ${JSON.stringify(faces)};\n`,
);
console.log(`src/report/fonts.js: ${faces.length} faces`);
